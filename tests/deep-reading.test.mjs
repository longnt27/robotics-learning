const figures=JSON.parse(fs.readFileSync(path.join(root,"content/paper-figures.json"),"utf8"));
const guides=JSON.parse(fs.readFileSync(path.join(root,"content/figure-guides.json"),"utf8"));
const countWords=(markdown)=>markdown
  .replace(/!\[[^\]]*\]\([^)]+\)/g,"")
  .replace(/https?:\/\/\S+/g,"")
  .split(/\s+/).filter(Boolean).length;

test("22 Vietnamese tutorials contain unique explanations instead of boilerplate",()=>{
  assert.equal(corpusSlugs.length,22);
  assert.deepEqual(Object.keys(figures).sort(),[...corpusSlugs].sort());
  assert.deepEqual(Object.keys(guides).sort(),[...corpusSlugs].sort());
  const totalFigures=Object.values(figures).reduce((n,items)=>n+items.length,0);
  assert.equal(totalFigures,167,"Do not silently drop paper figures");
  assert.ok(new Set(Object.values(figures).map(x=>x.length)).size>=3,
    "Each paper has a different appropriate number of figures");

  const observedHeadings=new Map();
  for(const slug of corpusSlugs){
    const content=fs.readFileSync(path.join(root,"content/papers",slug+".md"),"utf8");
    assert.ok(countWords(content)>=950,slug+": not enough reader-focused teaching material");
    assert.doesNotMatch(content,/<!-- (?:BEGIN|END) (?:EXTENDED WALKTHROUGH|ADDITIONAL PDF FIGURES) -->/,
      slug+": deprecated autogenerated sections must not be shipped");
    assert.doesNotMatch(content,/### Đào sâu:|#### Đọc hình gốc:|#### Ví dụ từng bước để hiểu cơ chế/,
      slug+": machine-templated explanations remain");
    assert.doesNotMatch(content,/Bài do bạn cung cấp|Xem caption đầy đủ trong PDF/,
      slug+": editor-only scaffolding leaked into prose");
    const sections=content.split(/(?=^## )/m).filter(x=>x.startsWith("## "));
    assert.equal(sections.length,8,slug+": expected eight educational sections");
    const headings=sections.map(section=>section.split("\n")[0]);
    for(const topic of ["Vì sao cần nghiên cứu này?","Phương pháp thực hiện",
      "Kết quả thực nghiệm","Hạn chế và câu hỏi còn mở","Liên hệ với nghiên cứu khác"]){
      assert.ok(headings.includes("## "+topic),slug+": missing "+topic);
    }
    for(const section of sections){
      const h=section.match(/^### ([^\n]+)$/m);
      assert.ok(h,slug+": section without a descriptive teaching subheading");
      const intro=section.replace(/!\[[^\]]*\]\([^)]+\)/g,"")
        .replace(/\[[^\]]+\]\([^)]+\)/g,"").trim();
      assert.ok(intro.split(/\s+/).length>=90,slug+": thin section "+section.split("\n")[0]);
      if(!/^### (?:Số liệu|Những bài nên đọc)/.test(h[0])){
        const seen=observedHeadings.get(h[1])||new Set();
        seen.add(slug);observedHeadings.set(h[1],seen);
      }
    }
    const textOnly=content
      .replace(/!\[[^\]]*\]\([^)]+\)/g,"")
      .replace(/\[[^\]]+\]\([^)]+\)/g,"")
      .replace(/\x60[^\x60]*\x60/g,"");
    assert.doesNotMatch(textOnly,/\b(?:model|dataset|baseline|training|input|output|pipeline|learned|generalization|understanding)\b/i,
      slug+": generic English jargon in Vietnamese prose");
    assert.doesNotMatch(textOnly,/Action đoạn hành động|action đoạn hành động|phòng phòng thí nghiệm|Vật lý Intelligence|bản mô hình đã lưu VLM/i,
      slug+": awkward mixed-language or double-translated phrase");
    // Editing the prose must never translate stable paper/figure URL slugs.
    for(const [,target] of content.matchAll(/\]\(\/paper\/([^)]+)\)/g)){
      assert.ok(corpusSlugs.includes(target),slug+": broken related-paper link: "+target);
    }
    assert.doesNotMatch(content,/Diffusion chính sách điều khiển|huấn luyện-time|\/paper-figures\/rtc-suy luận\//,
      slug+": literal research name or stable asset path was translated");
    const occurrences=[...content.matchAll(/!\[[^\]]*\]\((\/paper-figures\/[^)]+)\)/g)].map(x=>x[1]);
    assert.equal(new Set(occurrences).size,occurrences.length,slug+": a source figure is duplicated");
    assert.equal(occurrences.length,figures[slug].length,slug+": a source figure was lost");
    for(const fig of figures[slug]){
      assert.match(fig.caption,/^fig(?:ure)?\.?\s*\d+/i,slug+": original caption missing");
      assert.ok(fig.pdf.startsWith("https://"),slug+": missing original PDF");
      assert.ok(Number.isInteger(fig.page)&&fig.page>0,slug+": invalid PDF page");
      assert.equal(fig.bbox.length,4,slug+": missing figure crop");
      assert.ok(fig.image.startsWith("/paper-figures/"+slug+"/"));
      assert.ok(fs.existsSync(path.join(root,"public",fig.image)),slug+": missing figure asset "+fig.image);
      assert.ok(content.includes("]("+fig.image+")"),slug+": absent image "+fig.image);
      assert.ok(fig.caption_vi?.trim().length>=30,slug+": incomplete Vietnamese caption "+fig.number);
      assert.match(fig.caption_vi,/[àáạảãăâđèéẹẻẽêếìíịỉĩòóọỏõôốơớùúụủũưứỳýỵỷỹ]/i,
        slug+": caption lacks Vietnamese text "+fig.number);
      assert.equal(fig.translation_method,"manual-editorial-from-original-english",slug+": unreviewed translation "+fig.number);
      assert.equal(fig.translation_reviewed,true,slug+": not editorially reviewed "+fig.number);
      assert.equal(fig.caption_sha256,createHash("sha256").update(fig.caption).digest("hex"),
        slug+": English original changed without checking translation "+fig.number);
      assert.doesNotMatch(fig.caption_vi,/sự mài mòn|không bắn|biến áp vani|gợi ý mulitimodal|tổn thất huấn luyện|phòng phòng thí nghiệm|tường minh dự đoán hành động/i,
        slug+": known bad technical translation "+fig.number);
    }
    for(const key of ["overview","method","worked"]){
      assert.ok(guides[slug][key].split(/\s+/).length>=60,slug+": missing guide metadata "+key);
    }
  }
  for(const [heading,owners] of observedHeadings){
    assert.ok(owners.size<=2,"Too many tutorials reuse this supposedly explanatory title: "+heading);
  }
});

test("Markdown lessons keep readable headings and professional teaching prose",()=>{
  for(const slug of corpusSlugs){
    const content=fs.readFileSync(path.join(root,"content/papers",slug+".md"),"utf8");
    assert.doesNotMatch(content,/^#{2,6}\s+#{1,6}\s/m,
      slug+": doubled Markdown heading markers make the lesson harder to navigate");
    assert.doesNotMatch(content,/(?:^|[.!?]\s+)(?:mô hình|chính sách điều khiển|lần làm mẫu)\b/m,
      slug+": unedited lowercase sentence start");
    assert.doesNotMatch(content,/\b(?:mày|tao)\b/i,
      slug+": informal assistant voice leaked into the published lesson");
    assert.ok([...content.matchAll(/^### [^#\n]/gm)].length>=12,
      slug+": missing paper-specific teaching walkthroughs");
  }
});

test("Vietnamese proofreading does not reintroduce machine-like translations",()=>{
  for(const slug of corpusSlugs){
    const content=fs.readFileSync(path.join(root,"content/papers",slug+".md"),"utf8");
    const prose=content.replace(/!\[[^\]]*\]\([^)]+\)/g,"").replace(/https?:\/\/\S+/g,"");
    assert.doesNotMatch(prose,/lượt thao tác mẫu|phòng lab|lệnh motor|bộ điều khiển motor|cấp motor|hành động chunking|số số|lập lại kế hoạch/i,
      slug+": awkward literal translation or repeated words");
  }
  const act=fs.readFileSync(path.join(root,"content/papers/act.md"),"utf8");
  assert.match(act,/Action chunking/);
  const qwen=fs.readFileSync(path.join(root,"content/papers/qwen-vla.md"),"utf8");
  assert.doesNotMatch(qwen,/### Bốn chữ viết tắt trong quy trình huấn luyện/);
  assert.match(qwen,/### Ví dụ vì sao cần học chuyển động trước khi gắn với ảnh/);
  const octo=fs.readFileSync(path.join(root,"content/papers/octo.md"),"utf8");
  assert.doesNotMatch(octo,/^chính sách điều khiển từng học/gm);
});

